const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const context = {Live: {active: true, user: {role: 'super_admin'}}, escapeHtml: x => String(x ?? '').replaceAll('<','&lt;').replaceAll('>','&gt;')};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../registry.js'),'utf8')+'\nglobalThis.registry=Registry;',context);
const registry=context.registry;
registry.page='teachers';
registry.rows=[{id:1,code:'T01',full_name:'<Teacher>',branch_name:'North',department_name:'Education',job_title:'Teacher',status:'active'},{id:2,code:'T02',full_name:'Second',branch_name:'South',department_name:'Education',job_title:'Teacher',status:'inactive'}];
