const vm = require('node:vm');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync(require('node:path').join(__dirname, '../app.js'),'utf8');
const start = app.indexOf('function csvCell(');
const end = app.indexOf('\n$("#menu")', start);
assert.ok(start >= 0 && end > start, 'Export helpers must exist');
const source = app.slice(start, end);
const context = {state:{branches:[{code:'A',name:'Alpha',zone:'North'},{code:'B',name:'Beta',zone:'South'}]},current:'branches',filterZone:'all',filterText:''};
vm.createContext(context);vm.runInContext(source,context);
assert.equal(context.branchExportRows().length,2);
context.filterZone='North';assert.equal(context.branchExportRows()[0].code,'A');
context.filterText='Beta';assert.equal(context.branchExportRows().length,0);
context.filterZone='all';assert.equal(context.branchExportRows()[0].code,'B');
context.current='reports';assert.equal(context.branchExportRows().length,2);
assert.equal(context.csvCell('School "A", Kabul'),'"School ""A"", Kabul"');
for(const value of ['=1+1','+SUM(A1)','-1+2','@SUM(A1)','  =1','\ttext','\ntext']) assert.ok(context.csvCell(value).startsWith('"\''));
assert.equal(context.csvCell('صنف دهم'),'"صنف دهم"');
assert.equal(context.csvCell(null),'""');
console.log('PASS: filters, empty results, report export scope, CSV escaping, formula neutralization, Unicode and null values');
